#include <stdio.h>

int main(){

    //Declarando A
    float A;

    //Declarando B
    int B;

    //Imprimindo o texto de A
    printf("Digite o valor de A: ");
    //Recendo o valor de A
    scanf("%f", &A);
    //Imprimindo o valor de A
    printf("O valor de A: %f \n", A);

    //Imprimindo o texto de B
    printf("Digite o valor de B: ");
    //Recebendo o valor de B
    scanf("%i", &B);
    //Imprimindo o valor de B
    printf("O valor de B: %i \n", B);

    return 0;

}